/** Aplica COPY_FIXES a los campos de un programa y recuerda qué correcciones encontraron su texto. */
export function copyFixer() {
  const used = new Set<string>();
  const fix = (slug: string, s: string) => {
    for (const [i, [slugs, from, to]] of COPY_FIXES.entries()) {
      if (!slugs.includes(slug) || !s.includes(from)) continue;
      used.add(`${i}|${slug}`);
      s = s.split(from).join(to);
    }
    return s;
  };
  return {
    fields<T extends Record<string, unknown>>(slug: string, obj: T): T {
      return Object.fromEntries(
        Object.entries(obj).map(([k, v]) => [k, v == null ? v : typeof v === "string" ? fix(slug, v) : JSON.parse(fix(slug, JSON.stringify(v)))]),
      ) as T;
    },
    unused: (slugs: Iterable<string>) => {
      const seeded = new Set(slugs);
      return COPY_FIXES.flatMap(([ss, from], i) => ss.filter((s) => seeded.has(s) && !used.has(`${i}|${s}`)).map((s) => `${s}: «${from}»`));
    },
  };
}
